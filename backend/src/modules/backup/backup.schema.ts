export const restoreBackupSchema = z.strictObject({
  schemaVersion: z.literal(1),
  exportedAt: isoDateTimeString,
  sourceShopId: z.uuid(),
  checksumSha256: z.string().regex(/^[a-f0-9]{64}$/, 'Invalid SHA-256 checksum format'),
  data: backupDataSchema,
});

export type RestoreBackupInput = z.infer<typeof restoreBackupSchema>;

function canonicalizeValue(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map((item) => canonicalizeValue(item));
  }
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>).sort(([a], [b]) =>
      a.localeCompare(b),
    );
    const out: Record<string, unknown> = {};
    for (const [k, v] of entries) {
      out[k] = canonicalizeValue(v);
    }
    return out;
  }
  return value;
}

export function computeBackupChecksumSha256(data: unknown): string {
  const canonical = JSON.stringify(canonicalizeValue(data));
  return createHash('sha256').update(canonical, 'utf8').digest('hex');
}
